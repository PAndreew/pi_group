import assert from 'node:assert/strict'
import { chromium } from 'playwright'
const browser = await chromium.launch()
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 360 }, isMobile: true, hasTouch: true })
  await page.route('**/api/**', route => route.fulfill({ json: { users: [], folders: Array.from({ length: 40 }, (_, i) => `folder-${i}`) } }))
  await page.goto(`${process.env.TEST_URL || 'http://127.0.0.1:5173'}/test/fixtures/folder-composer.html`)
  const input = page.locator('textarea')
  await input.fill('/')
  const list = page.getByRole('listbox')
  const popup = page.locator('[data-suggestions]')
  await list.waitFor()
  for (const height of [360, 280, 500]) {
    await page.setViewportSize({ width: 390, height })
    await page.waitForTimeout(100)
    const box = await popup.boundingBox()
    const composer = await page.locator('[data-composer-box]').boundingBox()
    assert.ok(Math.abs(box.y + box.height + 4 - composer.y) < 2, 'dropup stays attached above composer')
    assert.equal(await popup.evaluate(el => getComputedStyle(el).zIndex), '100', 'dropup renders above navbar')
    assert.ok(box.height > 60, 'popup is not a narrow stripe')
    await page.getByRole('option').last().scrollIntoViewIfNeeded()
    assert.ok(await list.evaluate(el => el.scrollTop > 0), 'last folder scrolls into view')
    await input.press('Escape')
    await input.fill('')
    await input.fill('/')
    await list.waitFor()
  }
  // Model keyboard panning independently of a resize event: app geometry updates on rAF.
  await page.evaluate(() => {
    Object.defineProperty(window.visualViewport, 'offsetTop', { configurable: true, value: 70 })
    Object.defineProperty(window.visualViewport, 'height', { configurable: true, value: 300 })
    window.visualViewport.dispatchEvent(new Event('resize'))
  })
  await page.waitForTimeout(150)
  const panned = await popup.boundingBox(), composer = await page.locator('[data-composer-box]').boundingBox()
  assert.ok(Math.abs(panned.y + panned.height + 4 - composer.y) < 2, 'dropup remains attached after keyboard pan')
  await input.evaluate(el => { window.folderBlurCount = 0; el.addEventListener('blur', () => window.folderBlurCount++) })
  await page.getByRole('option').first().tap()
  const pill = page.getByRole('button', { name: 'Remove folder folder-0' })
  await pill.waitFor()
  assert.equal(await input.getAttribute('placeholder'), '', 'no placeholder with selected folder')
  assert.equal(await pill.locator('span').textContent(), 'folder-0', 'pill has no slash')
  assert.equal(await page.evaluate(() => window.folderBlurCount), 0, 'touch selection never blurs editor')
  await input.fill('hello')
  const pillBox = await pill.boundingBox(), inputBox = await input.boundingBox()
  assert.ok(pillBox.x < inputBox.x && pillBox.y < inputBox.y + inputBox.height, 'pill sits inline before text')
  await input.press('Home')
  await input.press('Backspace')
  assert.equal(await pill.count(), 0, 'backspace unwraps pill')
  assert.equal(await input.inputValue(), '/folder- hello', 'backspace deletes one folder character and preserves message')
  await list.waitFor()
  await input.press('Backspace')
  assert.equal(await input.inputValue(), '/folder hello', 'subsequent backspace deletes one more character')
  console.log('PASS: attached dropup, elevated stacking, scrolling, touch focus and Backspace suggestions')
} finally { await browser.close() }
